// Arithmetic Operators in JavaScript

// Addition (+)
let a = 10;
let b = 5;
let sum = a + b; // sum is 15

// Subtraction (-)
let difference = a - b; // difference is 5  
// Multiplication (*)
let product = a * b; // product is 50
// Division (/)
let quotient = a / b; // quotient is 2
// Modulus (%)
let remainder = a % b;
// remainder is 0
// Increment (++)
let c = 10;
c++;
// c is now 11
// Decrement (--)
let d = 10;
d--;
// d is now 9

// Exponentiation (**)
let e = 2;
let f = 3;
let power = e ** f; // power is 8 (2 raised to the power of 3)

console.log("Sum:", sum);
console.log("Difference:", difference);
console.log("Product:", product);
console.log("Quotient:", quotient);
console.log("Remainder:", remainder);
console.log("Incremented value of c:", c);
console.log("Decremented value of d:", d);
console.log("Power:", power);
