// Assignments operators are used to assign values to variables. The most common assignment operator is the equal sign (=), which assigns the value on the right to the variable on the left.

// Example:
let x = 10; // assigns the value 10 to the variable x
console.log("Initial value of x:", x); // Output: Initial value of x: 10
let y = 5;  // assigns the value 5 to the variable y
console.log("Initial value of y:", y); // Output: Initial value of y: 5

// There are also compound assignment operators that combine an arithmetic operation with assignment. These include:
// Addition assignment (+=)
x += 5; // equivalent to x = x + 5; now x is 15
console.log("After addition assignment, value of x:", x); // Output: After addition assignment, value of x: 15
// Subtraction assignment (-=)
y -= 2; // equivalent to y = y - 2; now y is 3
console.log("After subtraction assignment, value of y:", y); // Output: After subtraction assignment, value of y: 3
// Multiplication assignment (*=)
x *= 2; // equivalent to x = x * 2; now x is 30
console.log("After multiplication assignment, value of x:", x); // Output: After multiplication assignment, value of x: 30

// Division assignment (/=)
y /= 3; // equivalent to y = y / 3; now y is 1
console.log("After division assignment, value of y:", y); // Output: After division assignment, value of y: 1
console.log("Final value of x:", x); // Output: Final value of x: 30
// Modulus assignment (%=)
y %= 2; // equivalent to y = y % 2; now y is 1
console.log("After modulus assignment, value of y:", y); // Output: After modulus assignment, value of y: 1

// Exponentiation assignment (**=)
x **= 2; // equivalent to x = x ** 2; now x is 900 (30 raised to the power of 2)
console.log("After exponentiation assignment, value of x:", x); // Output: After exponentiation assignment, value of x: 900
// Increment assignment (++)
x++; // equivalent to x = x + 1; now x is 901
console.log("After increment assignment, value of x:", x); // Output: After increment assignment, value of x: 901
// Decrement assignment (--)
y--; // equivalent to y = y - 1; now y is 0
console.log("After decrement assignment, value of y:", y); // Output: After decrement assignment, value of y: 0
console.log("Final value of y:", y); // Output: Final value of y: 0
