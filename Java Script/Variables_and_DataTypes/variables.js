// `const` declares a constant variable that must be initialized immediately.
// Its binding cannot be reassigned after declaration.
// const account = 123456789;

// This would cause a TypeError because a `const` variable cannot be assigned
// a new value. It remains commented out so the program can run successfully.
// account = 23242385093;

// This would print the account number to the console.
// console.log(account);

